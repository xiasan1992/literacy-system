function isMastered(char) {
    const d = charsData[char];
    if (!d) return false;
    if (d.wrong === 0 && d.correct > 0) return true;
    if (d.streak >= 3) return true;
    if (d.streak === undefined && (d.correct - d.wrong >= 3)) return true;
    return false;
}

